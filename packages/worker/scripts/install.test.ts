// The build command (docs/operations.md section 3): the pnpm version read from mise.lock, the refusals, the command it
// runs with npx stubbed, and the version sources that must agree.
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { afterEach, beforeEach, describe, expect, it } from "vitest";

import { install, lockedPnpmVersion, nodeVersionProblem, type InstallIo } from "./install-run.ts";
import type { RunResult, TerminationSignal } from "./runner.ts";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");

const read = (path: string) => readFileSync(join(REPO, path), "utf8");

/** A lockfile as mise writes it, with the pnpm tables given. */
function lockfile(...pnpm: string[]): string {
  return [
    "# @generated - this file is auto-generated by `mise lock` https://mise.jdx.dev/dev-tools/mise-lock.html",
    "",
    "lockfile_version = 3",
    "",
    "[[tools.node]]",
    'version = "24.22.3"',
    'backend = "core:node"',
    'specifiers = ["24"]',
    "",
    ...pnpm,
    "",
    "[[tools.ghalint]]",
    'version = "1.6.0"',
    'backend = "aqua:suzuki-shunsuke/ghalint"',
  ].join("\n");
}

const pnpmTable = (version: string) =>
  [
    "[[tools.pnpm]]",
    `version = ${version}`,
    'backend = "aqua:pnpm/pnpm"',
    'specifiers = ["12"]',
    "",
    '[tools.pnpm."platforms.linux-x64"]',
    'checksum = "sha256:00"',
  ].join("\n");

describe("lockedPnpmVersion", () => {
  it("reads the version of the pnpm entry", () => {
    expect(lockedPnpmVersion(lockfile(pnpmTable('"12.20.0"')))).toEqual({ ok: true, version: "12.20.0" });
  });

  it("reads the repository's mise.lock", () => {
    expect(lockedPnpmVersion(read("mise.lock"))).toMatchObject({ ok: true, version: expect.stringMatching(/^\d+\./) });
  });

  it.each([
    ["no pnpm entry", lockfile(), "mise.lock has no [[tools.pnpm]] entry"],
    [
      "two pnpm entries",
      lockfile(pnpmTable('"12.20.0"'), pnpmTable('"11.9.0"')),
      "mise.lock pins more than one pnpm version",
    ],
    [
      "an entry whose version is only in a platform table",
      lockfile('[[tools.pnpm]]\n[tools.pnpm."platforms.linux-x64"]\nversion = "12.20.0"'),
      "the [[tools.pnpm]] entry of mise.lock has no version",
    ],
    ["a prefix", lockfile(pnpmTable('"12"')), 'not an exact version: version = "12"'],
    ["a prerelease", lockfile(pnpmTable('"12.20.0-rc.1"')), "not an exact version"],
    ["a literal string", lockfile(pnpmTable("'12.20.0'")), "not an exact version"],
    ["an option for npx", lockfile(pnpmTable('"--registry=https://example.com"')), "not an exact version"],
  ])("refuses %s", (_name, text, problem) => {
    const result = lockedPnpmVersion(text);
    expect(result.ok).toBe(false);
    expect(!result.ok && result.problem).toContain(problem);
  });
});

describe("nodeVersionProblem", () => {
  it.each([
    ["24", "24.22.3"],
    ["24\n", "24.22.3"],
    ["v24.22", "24.22.3"],
    ["24.22.3", "24.22.3"],
  ])("accepts .node-version %j for Node %s", (wanted, running) => {
    expect(nodeVersionProblem(wanted, running)).toBeUndefined();
  });

  it.each([
    ["24", "22.23.2", "this is Node 22.23.2, but .node-version asks for 24"],
    ["24", "240.0.0", "asks for 24"],
    ["24.22.3", "24.22.1", "asks for 24.22.3"],
    ["lts/*", "24.22.3", '.node-version is not a Node version: "lts/*"'],
    ["", "24.22.3", '.node-version is not a Node version: ""'],
  ])("refuses .node-version %j for Node %s", (wanted, running, problem) => {
    expect(nodeVersionProblem(wanted, running)).toContain(problem);
  });
});

type RunOptions = {
  readonly env?: Record<string, string>;
  readonly args?: string[];
  readonly nodeVersion?: string;
  readonly answer?: (signal: AbortSignal) => Promise<RunResult>;
};

describe("install", () => {
  let dir: string;
  let lines: string[];
  let listeners: ((signal: TerminationSignal) => void)[];

  beforeEach(() => {
    dir = mkdtempSync(join(tmpdir(), "install-test-"));
    writeFileSync(join(dir, "mise.lock"), lockfile(pnpmTable('"12.20.0"')));
    writeFileSync(join(dir, ".node-version"), "24\n");
    lines = [];
    listeners = [];
  });

  afterEach(() => {
    rmSync(dir, { recursive: true, force: true });
  });

  /** Runs the script with npx stubbed: each call records its arguments. */
  async function run(options: RunOptions = {}): Promise<{ status: number; calls: (readonly string[])[] }> {
    const calls: (readonly string[])[] = [];
    const io: InstallIo = {
      repoDir: dir,
      env: options.env ?? {},
      args: options.args ?? [],
      nodeVersion: options.nodeVersion ?? "24.22.3",
      run: async (args, signal) => {
        calls.push(args);
        return options.answer === undefined ? { ok: true } : options.answer(signal);
      },
      log: (line) => lines.push(line),
      onSignal: (listener) => {
        listeners.push(listener);
        return () => listeners.splice(listeners.indexOf(listener), 1);
      },
    };
    return { status: await install(io), calls };
  }

  const INSTALL = ["--yes", "pnpm@12.20.0", "install", "--frozen-lockfile"];

  it("installs with the pnpm of mise.lock, once", async () => {
    const { status, calls } = await run();
    expect(calls).toEqual([INSTALL]);
    expect(status).toBe(0);
    expect(lines).toEqual(["install: pnpm 12.20.0 from mise.lock", "install: done"]);
    expect(listeners).toEqual([]);
  });

  it("runs in Workers Builds when SKIP_DEPENDENCY_INSTALL is set", async () => {
    for (const skip of ["1", "true"]) {
      const { status, calls } = await run({ env: { WORKERS_CI: "1", SKIP_DEPENDENCY_INSTALL: skip } });
      expect([status, calls]).toEqual([0, [INSTALL]]);
    }
  });

  const refusals: [name: string, arrange: () => void, options: RunOptions, problem: string][] = [
    ["a missing mise.lock", () => rmSync(join(dir, "mise.lock")), {}, "mise.lock cannot be read (ENOENT)"],
    [
      "a mise.lock without pnpm",
      () => writeFileSync(join(dir, "mise.lock"), lockfile()),
      {},
      "mise.lock has no [[tools.pnpm]] entry",
    ],
    ["a missing .node-version", () => rmSync(join(dir, ".node-version")), {}, ".node-version cannot be read (ENOENT)"],
    ["another Node major", () => undefined, { nodeVersion: "22.23.2" }, "this is Node 22.23.2"],
    [
      "Workers Builds without SKIP_DEPENDENCY_INSTALL",
      () => undefined,
      { env: { WORKERS_CI: "1" } },
      "SKIP_DEPENDENCY_INSTALL is not set to 1",
    ],
    [
      "Workers Builds with SKIP_DEPENDENCY_INSTALL=0",
      () => undefined,
      { env: { WORKERS_CI: "1", SKIP_DEPENDENCY_INSTALL: "0" } },
      "SKIP_DEPENDENCY_INSTALL is not set to 1",
    ],
  ];

  it.each(refusals)("refuses %s and runs nothing", async (_name, arrange, options, problem) => {
    arrange();
    const { status, calls } = await run(options);
    expect([status, calls]).toEqual([1, []]);
    expect(lines[0]).toBe("install: refused; nothing was run");
    expect(lines.slice(1)).toEqual([expect.stringContaining(problem)]);
  });

  it("names every problem at once", async () => {
    rmSync(join(dir, "mise.lock"));
    const { status } = await run({ nodeVersion: "22.23.2", env: { WORKERS_CI: "1" } });
    expect(status).toBe(1);
    expect(lines).toHaveLength(4);
  });

  it("refuses arguments", async () => {
    const { status, calls } = await run({ args: ["--prod"] });
    expect([status, calls]).toEqual([1, []]);
  });

  it("fails when the install fails", async () => {
    const { status } = await run({ answer: async () => ({ ok: false, reason: "exited with code 1" }) });
    expect(status).toBe(1);
    expect(lines).toContain("install: npx pnpm@12.20.0 exited with code 1");
    expect(listeners).toEqual([]);
  });

  it("stops the install on a signal", async () => {
    let stopped = false;
    const { status, calls } = await run({
      answer: (signal) => {
        queueMicrotask(() => listeners[0]?.("SIGINT"));
        return new Promise((resolve) =>
          signal.addEventListener("abort", () => {
            stopped = signal.reason === "SIGINT";
            resolve({ ok: false, reason: "was stopped" });
          }),
        );
      },
    });
    expect(stopped).toBe(true);
    expect(calls).toHaveLength(1);
    expect(status).toBe(130);
    expect(lines).toContain("install: stopped by SIGINT");
    expect(listeners).toEqual([]);
  });

  it("stops listening for signals when the runner throws", async () => {
    await expect(run({ answer: () => Promise.reject(new Error("boom")) })).rejects.toThrow("boom");
    expect(listeners).toEqual([]);
  });
});

// .node-version at the repository root is the one source of the Node version: mise reads it (mise.toml enables it),
// packages/worker/.node-version links to it for Workers Builds, and engines.node repeats its major for pnpm.
describe("the Node version", () => {
  const nodeVersion = read(".node-version").trim();

  it("is a major, so the mise update workflow moves mise.lock within it", () => {
    expect(nodeVersion).toMatch(/^\d+$/);
  });

  it("is what Workers Builds reads in the build's root directory", () => {
    expect(read("packages/worker/.node-version").trim()).toBe(nodeVersion);
  });

  it("is not declared in mise.toml as well", () => {
    expect(read("mise.toml")).not.toMatch(/^\s*node\s*=/m);
    expect(read("mise.toml")).toMatch(/^idiomatic_version_file_enable_tools = \["node"\]$/m);
  });

  it.each(["package.json", "packages/cli/package.json"])("matches engines.node in %s", (file) => {
    const manifest: unknown = JSON.parse(read(file));
    expect(manifest).toMatchObject({ engines: { node: `${nodeVersion}.x` } });
  });
});
